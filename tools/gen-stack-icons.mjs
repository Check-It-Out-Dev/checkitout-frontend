// Generates src/app/feature/survey/showcases/stack-icons.ts from simple-icons.
//
// The technical survey's stack strip names ~35 technologies. Text chips read as
// a list; a brand mark per chip reads as the thing itself, and it is what the
// owner asked for. The marks come from simple-icons (CC0), pinned in
// devDependencies, and are copied here at generation time so the app bundles
// only the paths it uses (the package is 3,400 icons) and never fetches a logo
// at runtime. Re-run after changing STACK below or bumping simple-icons:
//
//   node tools/gen-stack-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src', 'app', 'feature', 'survey', 'showcases', 'stack-icons.ts');

/** simple-icons slug per technology label as the strip shows it. `null` means
 * no brand mark exists (a house product or an obscure library): the chip falls
 * back to a Material glyph named in the component. */
const STACK = {
  'Angular 22': 'angular',
  TypeScript: 'typescript',
  'Tailwind CSS': 'tailwindcss',
  'Angular Material': 'materialdesign',
  'Transloco (i18n)': null,
  RxJS: 'reactivex',
  'Spring Boot 3.4': 'springboot',
  'Java 21': 'openjdk',
  Maven: 'apachemaven',
  Liquibase: 'liquibase',
  PostgreSQL: 'postgresql',
  'Redis · Sentinel': 'redis',
  Firestore: 'firebase',
  'Google KMS': 'googlecloud',
  'Google Secret Manager': 'googlecloud',
  Docker: 'docker',
  Nginx: 'nginx',
  Cloudflare: 'cloudflare',
  Ansible: 'ansible',
  'GitHub Actions': 'githubactions',
  OVH: 'ovh',
  Grafana: 'grafana',
  Loki: 'grafana',
  'Grafana Alloy': 'grafana',
  'Journald (sealed)': 'linux',
  'Google Cloud Storage': 'googlecloud',
  Stripe: 'stripe',
  Fakturownia: null,
  KSeF: null,
  'Firebase Auth': 'firebase',
  'Instagram / Meta': 'instagram',
  'RBAC · JWT claims': 'jsonwebtokens',
};

// the package's exports map hides package.json from require.resolve
const pkg = join(here, '..', 'node_modules', 'simple-icons');
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
const marks = {};
for (const slug of new Set(Object.values(STACK).filter(Boolean))) {
  const svg = readFileSync(join(pkg, 'icons', `${slug}.svg`), 'utf8');
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  const title = /<title>([^<]+)<\/title>/.exec(svg)?.[1];
  if (!path || !title) throw new Error(`simple-icons: no path/title in ${slug}.svg`);
  marks[slug] = { title, path };
}
const data = JSON.parse(readFileSync(join(pkg, 'data', 'simple-icons.json'), 'utf8'));
const icons = Array.isArray(data) ? data : data.icons;
const hexOf = new Map(
  icons.map((i) => [i.slug ?? i.title.toLowerCase().replace(/[^a-z0-9]/g, ''), i.hex]),
);
for (const slug of Object.keys(marks)) {
  const hex = hexOf.get(slug);
  if (!hex) throw new Error(`simple-icons: no brand colour for ${slug}`);
  marks[slug].hex = `#${hex}`;
}

const lines = [
  `// GENERATED by tools/gen-stack-icons.mjs from simple-icons ${version} (CC0). Do not edit.`,
  `// One 24×24 path per brand, with its published colour; labels map to a mark or to null.`,
  '',
  'export interface StackMark {',
  '  readonly title: string;',
  '  readonly hex: string;',
  '  readonly path: string;',
  '}',
  '',
  'export const STACK_MARKS: Readonly<Record<string, StackMark>> = {',
  ...Object.entries(marks)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([slug, m]) =>
        `  ${slug}: { title: ${JSON.stringify(m.title)}, hex: '${m.hex}', path: ${JSON.stringify(m.path)} },`,
    ),
  '};',
  '',
  '/** Technology label → simple-icons slug, or null when no brand mark exists. */',
  'export const STACK_MARK_OF: Readonly<Record<string, string | null>> = {',
  ...Object.entries(STACK).map(
    ([label, slug]) => `  ${JSON.stringify(label)}: ${JSON.stringify(slug)},`,
  ),
  '};',
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(
  `wrote ${OUT}: ${Object.keys(marks).length} marks for ${Object.keys(STACK).length} labels`,
);
